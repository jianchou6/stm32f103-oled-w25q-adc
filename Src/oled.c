void I2C_Delay_us(uint16_t t)
{
	uint16_t i,j;
	for(i=0;i<t;i++)
		for(j=0;j<72;j++);
}

// 发送1字节，返回ACK：0=收到应答，1=无应答
uint8_t I2C_WriteByte(uint8_t dat)
{
	uint8_t i,ack;
	for(i=0;i<8;i++)
	{
		SCL_L;
		if(dat & 0x80) SDA_H;
		else SDA_L;
		dat <<= 1;
		I2C_Delay_us(2);
		SCL_H;
		I2C_Delay_us(2);
	}
	SCL_L;
	SDA_H; // 释放SDA，等待从机ACK
	I2C_Delay_us(2);
	SCL_H;
	ack = SDA_R; // 读取ACK，低电平=ACK成功
	SCL_L;
	return ack;
}

//起始
void I2C_Start(void)
{
	SDA_H;
	SCL_H;
	I2C_Delay_us(5);
	SDA_L;
	I2C_Delay_us(5);
	SCL_L;
}

void I2C_Stop(void)
{
	SDA_L;
	SCL_H;
	I2C_Delay_us(5);
	SDA_H;
	I2C_Delay_us(5);
}

//写数据
void OLED_Write_Data(uint8_t data)
{
    I2C_Start();
    I2C_WriteByte(OLED_ADDR);    //从机地址
    I2C_WriteByte(0x40);         //0x40：后续字节为【数据】
    // 重点：字模数据在这里做位反转！！
    I2C_WriteByte(data );
    I2C_Stop();
}

//写命令，保持原样，不要ReverseBit！！
void OLED_Write_Cmd(uint8_t cmd)
{
    I2C_Start();
    I2C_WriteByte(OLED_ADDR);
    I2C_WriteByte(0x00);        //0x00：后续字节为【命令】
    I2C_WriteByte(cmd);
    I2C_Stop();
}



//设置坐标 x:0~127，y:0~7(页)
void OLED_Set_Pos(uint8_t x, uint8_t y)
{
    OLED_Write_Cmd(0xb0 + y);

    OLED_Write_Cmd(((x & 0xf0) >> 4) | 0x10);
    OLED_Write_Cmd(x & 0x0f);
}

//清屏
void OLED_Clear(void)
{
	uint8_t y,x;
	for(y=0;y<8;y++)
	{
		OLED_Write_Cmd(0xB0+y);
		OLED_Write_Cmd(0x00);
		OLED_Write_Cmd(0x10);
		for(x=0;x<128;x++)
		{
			OLED_Write_Data(0x00);
		}
	}
}
