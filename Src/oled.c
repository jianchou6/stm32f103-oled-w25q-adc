// 显示一个字符（8×16 字库）
void OLED_ShowChar(uint8_t x, uint8_t y, char ch)
{
    uint8_t i;
    uint8_t c;

    if(ch < ' ' || ch > '~') return;   // 只支持可打印字符
    c = ch - ' ';                       // 转成字库序号（0~94）


        // 上半页：8 个字节
        OLED_Set_Pos(x, y);
        for(i = 0; i < 8; i++)
        {
            OLED_Write_Data(F8X16[c * 16 + i]);
        }
        // 下半页：8 个字节
        OLED_Set_Pos(x, y + 1);
        for(i = 0; i < 8; i++)
        {
            OLED_Write_Data(F8X16[c * 16 + 8 + i]);
        }

}
// 显示数字（额外函数，与 OLED_ShowChar 区分开）
void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    uint8_t t, temp;
    uint8_t enshow = 0;
    uint32_t divisor = 1;

    for(t = 0; t < len - 1; t++) divisor *= 10;

    for(t = 0; t < len; t++)
    {
        temp = num / divisor;
        num = num % divisor;
        divisor /= 10;

        if(enshow == 0 && t < (len - 1))
        {
            if(temp == 0)
            {
                OLED_Set_Pos(x, y);
                for(uint8_t i = 0; i < 8; i++) OLED_Write_Data(0x00);

                OLED_Set_Pos(x, y + 1);
                for(uint8_t i = 0; i < 8; i++) OLED_Write_Data(0x00);

                x += 8;
                continue;
            }
            else enshow = 1;
        }

        OLED_ShowChar(x, y, temp + '0');   // 调用 OLED_ShowChar
        x += 8;
    }
}
// 显示字符串
void OLED_ShowString(uint8_t x, uint8_t y, char *str)
{

    while(*str != '\0')
    {
    	if(x>120 || y>6)break;
    	OLED_ShowChar(x, y, *str);
        x += 8;                          // 每个字符占 8 列
        if(x > 120)                      // 换行
        {
            x = 0;
            y += 2;                      // 8×16 字体占 2 页
        }
        str++;
    }
}


